// Generates TypeScript types for the Uzu API from its OpenAPI description.
//
//   npm run api:generate                      reads ../api/openapi.json, writes src/api/schema.d.ts
//   node scripts/generate-api.mjs <in> <out>  custom paths (used to try the script)
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, relative, resolve } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

import openapiTS, { astToString } from 'openapi-typescript';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const input = resolve(process.argv[2] ?? resolve(root, '../api/openapi.json'));
const output = resolve(process.argv[3] ?? resolve(root, 'src/api/schema.d.ts'));

if (!existsSync(input)) {
  console.error(
    `api:generate — OpenAPI description not found: ${input}\n` +
      'The API publishes it at api/openapi.json when it is built (see api/README.md). ' +
      'Build the API or merge the branch that adds it, then run `npm run api:generate` again.',
  );
  process.exit(1);
}

try {
  JSON.parse(readFileSync(input, 'utf8'));
} catch (error) {
  console.error(`api:generate — ${input} is not valid JSON: ${error.message}`);
  process.exit(1);
}

const ast = await openapiTS(pathToFileURL(input));
const header =
  '/**\n' +
  ' * Generated by `npm run api:generate` from api/openapi.json. Do not edit by hand.\n' +
  ' */\n\n';
mkdirSync(dirname(output), { recursive: true });
writeFileSync(output, header + astToString(ast));
console.log(`api:generate — wrote ${relative(process.cwd(), output)}`);
